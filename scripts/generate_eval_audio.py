#!/usr/bin/env python3
"""Generate synthetic CC0 WAV fixtures under evals/audio/ (JOE-1731)."""
from __future__ import annotations

import math
import struct
import wave
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "evals" / "audio"
RATE = 16000


def write_wav(path: Path, samples: list[float]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with wave.open(str(path), "w") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(RATE)
        frames = b"".join(
            struct.pack("<h", max(-32767, min(32767, int(s * 32767)))) for s in samples
        )
        w.writeframes(frames)


def silence(seconds: float = 1.0) -> list[float]:
    return [0.0] * int(RATE * seconds)


def tone(hz: float = 440.0, seconds: float = 1.0, amp: float = 0.2) -> list[float]:
    n = int(RATE * seconds)
    return [amp * math.sin(2 * math.pi * hz * i / RATE) for i in range(n)]


def main() -> None:
    write_wav(OUT / "silence_1s.wav", silence(1.0))
    write_wav(OUT / "tone_440_1s.wav", tone(440.0, 1.0))
    (OUT / "README.md").write_text(
        "# Synthetic eval audio (CC0)\n\n"
        "Generated by `scripts/generate_eval_audio.py`.\n\n"
        "- `silence_1s.wav` — 1 s mono 16 kHz silence (silence false-positive checks)\n"
        "- `tone_440_1s.wav` — 1 s 440 Hz tone (non-speech / noise marker)\n\n"
        "These are **not** speech. Multi-accent licensed speech corpora are external "
        "and use the same `evals/corpus.*.json` schema.\n",
        encoding="utf-8",
    )
    print(f"wrote fixtures under {OUT}")


if __name__ == "__main__":
    main()
